    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String mensaje = jTextField1.getText().trim();

if (mensaje.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Escribe un mensaje primero.");
    return;
}

// Ejecutar el envío/recepción en un hilo separado para no bloquear la GUI
new Thread(() -> {
    String respuesta = cliente.enviarMensaje(mensaje);

    // Actualizar la interfaz de forma segura
    javax.swing.SwingUtilities.invokeLater(() -> {
        jTextField2.setText(respuesta);
    });

    // Si el usuario quiere cerrar
    if ("cerrar".equalsIgnoreCase(mensaje)) {
        cliente.cerrar();
        javax.swing.SwingUtilities.invokeLater(() -> {
            jButton1.setEnabled(false);
            JOptionPane.showMessageDialog(this, "Conexión cerrada con el servidor.");
        });
    }
}).start();

            
    }//GEN-LAST:event_jButton1ActionPerformed

