    private void inicializarCliente() {
        cliente = new Cliente();
        boolean conectado = cliente.conectar("127.0.0.1", 5000);

        if (conectado) {
            String bienvenida = cliente.recibirMensajeInicial();
            jTextField2.setText(bienvenida);
        } else {
            JOptionPane.showMessageDialog(this, " No se pudo conectar con el servidor.");
            jButton1.setEnabled(false);
        }
    }

